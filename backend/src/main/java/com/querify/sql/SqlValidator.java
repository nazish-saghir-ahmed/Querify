package com.querify.sql;

import com.querify.exception.SqlSecurityException;
import net.sf.jsqlparser.JSQLParserException;
import net.sf.jsqlparser.parser.CCJSqlParserUtil;
import net.sf.jsqlparser.statement.Statement;
import net.sf.jsqlparser.statement.select.PlainSelect;
import net.sf.jsqlparser.statement.select.Select;
import net.sf.jsqlparser.statement.select.Limit;
import net.sf.jsqlparser.expression.LongValue;
import net.sf.jsqlparser.util.TablesNamesFinder;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

import java.util.Arrays;
import java.util.HashSet;
import java.util.List;
import java.util.Locale;
import java.util.Set;

/**
 * Robust SQL Security & Structural Validator.
 * Uses syntax-aware lexical scanning and JSqlParser AST analysis to guarantee:
 * 1. Read-only SELECT semantics (blocking INSERT, UPDATE, DELETE, DROP, ALTER, TRUNCATE).
 * 2. Strict table whitelisting (only approved domain tables can be queried).
 * 3. Prohibition of multi-statement injection/chaining while permitting a single trailing semicolon.
 * 4. Syntax-aware distinction of semicolons inside quoted literals ('Acme; Inc') and comments.
 * 5. Bounded query execution with automatic LIMIT injection.
 */
@Component
public class SqlValidator {

    private static final Logger log = LoggerFactory.getLogger(SqlValidator.class);

    private static final Set<String> ALLOWED_TABLES = new HashSet<>(Arrays.asList(
            "companies",
            "ai_models",
            "financial_performance",
            "ai_investments",
            "research_projects",
            "market_performance"
    ));

    private static final Set<String> FORBIDDEN_KEYWORDS = new HashSet<>(Arrays.asList(
            "insert", "update", "delete", "drop", "alter", "truncate",
            "grant", "revoke", "create", "replace", "execute", "exec",
            "call", "sleep", "benchmark", "outfile", "dumpfile",
            "load_file", "information_schema", "performance_schema",
            "mysql", "sys", "dual"
    ));

    @Value("${querify.query.max-limit:100}")
    private int maxLimit = 100;

    /**
     * Validates and sanitizes the given SQL query string.
     * 
     * @param rawSql The SQL string generated by AI or submitted for execution.
     * @return A sanitized, safe SQL query string with guaranteed SELECT semantics and safe LIMIT.
     * @throws SqlSecurityException If any security rule is breached.
     */
    public String validateAndSanitize(String rawSql) {
        if (rawSql == null || rawSql.trim().isEmpty()) {
            throw new SqlSecurityException("SQL query cannot be empty");
        }

        String cleaned = rawSql.trim();

        // Strip markdown code block wrappers if present (e.g. ```sql ... ```)
        if (cleaned.startsWith("```")) {
            cleaned = cleaned.replaceAll("^```(?:sql)?\\s*", "").replaceAll("\\s*```$", "").trim();
        }

        // 1. Syntax-aware multi-statement injection check
        // Allows a single trailing semicolon (standard SQL statement terminator),
        // but strictly blocks statement chaining (e.g. SELECT 1; DROP TABLE companies;).
        // Correctly ignores semicolons inside single/double quotes ('Acme; Inc') and comments.
        if (hasMultipleStatements(cleaned)) {
            throw new SqlSecurityException("Multiple SQL statements in a single execution are strictly prohibited.");
        }

        // Normalize trailing semicolon for JSqlParser AST analysis
        String normalizedSql = cleaned.endsWith(";") ? cleaned.substring(0, cleaned.length() - 1).trim() : cleaned;

        // 2. AST Parsing with JSqlParser
        Statement statement;
        try {
            statement = CCJSqlParserUtil.parse(normalizedSql);
        } catch (JSQLParserException e) {
            log.warn("SQL syntax parsing error: {}", e.getMessage());
            throw new SqlSecurityException("Invalid SQL syntax or structural violation: " + e.getMessage());
        }

        // 3. Ensure statement is strictly a SELECT
        if (!(statement instanceof Select)) {
            throw new SqlSecurityException("Only read-only SELECT queries are permitted. Database modifications (INSERT, UPDATE, DELETE, DROP, ALTER) are blocked.");
        }

        Select selectStatement = (Select) statement;

        // 4. Extract and validate all referenced tables
        TablesNamesFinder tablesFinder = new TablesNamesFinder();
        List<String> extractedTables = tablesFinder.getTableList((Statement) selectStatement);

        if (extractedTables.isEmpty()) {
            throw new SqlSecurityException("The query must reference at least one valid database table.");
        }

        for (String rawTable : extractedTables) {
            String sanitizedTable = normalizeIdentifier(rawTable);
            if (!ALLOWED_TABLES.contains(sanitizedTable)) {
                throw new SqlSecurityException("Access to unauthorized or system table '" + rawTable + 
                        "' is forbidden. Only approved domain tables can be queried: " + ALLOWED_TABLES);
            }
        }

        // 5. Keyword blocklist double-check on whole query
        String lowerCaseSql = cleaned.toLowerCase(Locale.ROOT);
        for (String forbidden : FORBIDDEN_KEYWORDS) {
            if (lowerCaseSql.matches("(?i).*\\b" + forbidden + "\\b.*")) {
                throw new SqlSecurityException("Query contains forbidden keyword or construct: " + forbidden);
            }
        }

        // 6. Enforce safe row LIMIT
        return enforceLimit(selectStatement, normalizedSql);
    }

    /**
     * Scans the SQL query in a syntax-aware manner to detect multiple statements.
     * Correctly handles quotes ('...', "...") and SQL comments (-- and /* ... *\/).
     * Returns true if multiple statements are detected outside of literals and comments.
     */
    public boolean hasMultipleStatements(String sql) {
        if (sql == null) return false;
        boolean inSingleQuote = false;
        boolean inDoubleQuote = false;
        boolean inLineComment = false;
        boolean inBlockComment = false;
        int len = sql.length();

        for (int i = 0; i < len; i++) {
            char c = sql.charAt(i);
            char next = (i + 1 < len) ? sql.charAt(i + 1) : '\0';

            // Check comments (when not inside string literals)
            if (!inSingleQuote && !inDoubleQuote) {
                if (!inBlockComment && c == '-' && next == '-') {
                    inLineComment = true;
                    i++;
                    continue;
                }
                if (!inLineComment && c == '/' && next == '*') {
                    inBlockComment = true;
                    i++;
                    continue;
                }
                if (inLineComment && (c == '\n' || c == '\r')) {
                    inLineComment = false;
                    continue;
                }
                if (inBlockComment && c == '*' && next == '/') {
                    inBlockComment = false;
                    i++;
                    continue;
                }
            }

            if (inLineComment || inBlockComment) {
                continue;
            }

            // Check quotes
            if (c == '\'' && !inDoubleQuote) {
                if (inSingleQuote && next == '\'') {
                    i++; // skip escaped single quote ''
                    continue;
                }
                inSingleQuote = !inSingleQuote;
                continue;
            }
            if (c == '"' && !inSingleQuote) {
                if (inDoubleQuote && next == '"') {
                    i++; // skip escaped double quote ""
                    continue;
                }
                inDoubleQuote = !inDoubleQuote;
                continue;
            }

            // Semicolon check outside quotes and comments
            if (!inSingleQuote && !inDoubleQuote && c == ';') {
                // Check if this is followed by any non-whitespace characters
                String remainder = sql.substring(i + 1).trim();
                if (!remainder.isEmpty()) {
                    // Non-empty remainder after semicolon -> statement chaining detected!
                    return true;
                }
            }
        }
        return false;
    }

    private String normalizeIdentifier(String identifier) {
        if (identifier == null) return "";
        String s = identifier.trim().toLowerCase(Locale.ROOT);
        s = s.replace("`", "").replace("\"", "").replace("'", "");
        if (s.contains(".")) {
            s = s.substring(s.lastIndexOf('.') + 1);
        }
        return s;
    }

    private String enforceLimit(Select selectStatement, String originalSql) {
        try {
            PlainSelect plainSelect = selectStatement.getPlainSelect();
            if (plainSelect != null) {
                Limit limit = plainSelect.getLimit();
                if (limit == null) {
                    plainSelect.setLimit(new Limit().withRowCount(new LongValue(maxLimit)));
                    return plainSelect.toString();
                } else if (limit.getRowCount() instanceof LongValue) {
                    long currentLimit = ((LongValue) limit.getRowCount()).getValue();
                    if (currentLimit > maxLimit || currentLimit <= 0) {
                        plainSelect.setLimit(new Limit().withRowCount(new LongValue(maxLimit)));
                        return plainSelect.toString();
                    }
                }
                return selectStatement.toString();
            }
        } catch (Exception e) {
            log.debug("Falling back to string-based limit enforcement: {}", e.getMessage());
        }

        // Fallback string-based limit check
        String trimmed = originalSql.endsWith(";") ? originalSql.substring(0, originalSql.length() - 1).trim() : originalSql;
        if (!trimmed.toLowerCase(Locale.ROOT).matches(".*\\blimit\\s+\\d+.*")) {
            return trimmed + " LIMIT " + maxLimit;
        }
        return trimmed;
    }
}
